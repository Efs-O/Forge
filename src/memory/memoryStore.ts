import { createHash, randomUUID } from 'crypto';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import type * as vscode from 'vscode';
import { workspaceIdFor } from '../remote/RemoteWorkspaceHandoff';
import { writeFileAtomicSync } from '../util/atomicWrite';

export interface StoredMemory {
  key: string;
  description: string;
  value: string;
  fileName: string;
  updated: string;
}

const KEY_PREFIX = 'forge.memory.';
const KEYS_INDEX = 'forge.memory.__keys__';
const DESCRIPTIONS_INDEX = 'forge.memory.__descriptions__';
const RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\..*)?$/iu;
const SAFE = /^[A-Za-z0-9._-]+$/u;
const INDEX_HEADER = '<!-- Generated by Forge. Edit the memory files, not this index. -->';

export function memoryFolderFor(workspaceRoot: string, home = os.homedir()): string {
  const baseName = path.basename(path.resolve(workspaceRoot));
  const shortId = workspaceIdFor(workspaceRoot).slice(0, 8);
  return path.join(home, '.forge', 'memories', `${baseName}-${shortId}`);
}

function yamlString(value: string): string {
  return /^[A-Za-z0-9][A-Za-z0-9 .,_()/-]*$/u.test(value) ? value : JSON.stringify(value);
}

function descriptionFor(value: string, description?: string): string {
  const explicit = description?.trim();
  if (explicit) return explicit.replace(/[\r\n]+/gu, ' ').trim();
  const first =
    value
      .split(/\r\n|\r|\n/u)
      .find((line) => line.trim().length > 0)
      ?.trim() ?? '';
  const summary = first.length > 120 ? `${first.slice(0, 120)}…` : first;
  return summary || '(empty memory)';
}

function slug(key: string): string {
  return (
    key
      .toLowerCase()
      .replace(/[^a-z0-9._-]+/gu, '-')
      .replace(/^-+|-+$/gu, '')
      .slice(0, 48) || 'memory'
  );
}

function hashedName(key: string): string {
  return `${slug(key)}-${createHash('sha256').update(key).digest('hex').slice(0, 6)}.md`;
}

function parseMemory(fileName: string, content: string): StoredMemory {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n\r?\n([\s\S]*)$/u.exec(content);
  if (!match) throw new Error('invalid or incomplete frontmatter');
  const fields = new Map<string, string>();
  for (const line of match[1]!.split(/\r?\n/u)) {
    const field = /^(name|description|updated):\s*(.*)$/u.exec(line);
    if (!field || fields.has(field[1]!)) throw new Error('invalid frontmatter fields');
    let value = field[2]!;
    if (value.startsWith('"')) {
      try {
        const parsed: unknown = JSON.parse(value);
        if (typeof parsed !== 'string') throw new Error('not a string');
        value = parsed;
      } catch {
        throw new Error(`invalid ${field[1]} value`);
      }
    }
    fields.set(field[1]!, value);
  }
  const key = fields.get('name');
  const description = fields.get('description');
  const updated = fields.get('updated');
  if (!key || !description?.trim() || !updated || !Number.isFinite(Date.parse(updated))) {
    throw new Error('missing or invalid name, description, or updated field');
  }
  return { key, description, value: match[2]!, fileName, updated };
}

/**
 * One file, one durable write: the shared atomic writer, not a local copy.
 *
 * The local version this replaces renamed a plain writeFileSync over a fixed
 * `<name>.tmp`, which cost two things. It never flushed, so a power loss could
 * keep the renamed file's size and lose its data - the exact failure
 * `util/atomicWrite.ts` documents - and the temp name was predictable, so every
 * extension host writing the same file raced on it. That was not two saves of
 * one note: `regenerateIndex` rewrites `MEMORY.md` on every write and every
 * forget, so any two windows remembering anything at the same moment were
 * writing the same temp name, and the loser got ENOENT (its temp had already
 * been renamed away) or a Windows EPERM.
 */
function atomicWrite(filePath: string, content: string): void {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileAtomicSync(filePath, content);
}

export class MemoryStore {
  private legacyPending: Promise<void> = Promise.resolve();
  private readonly fallbackToMemento: boolean;

  constructor(
    readonly directory: string,
    private readonly state: vscode.Memento,
    fallbackToMemento = false,
    readonly migrationFailureReason?: string,
    private readonly writeAtomic: typeof atomicWrite = atomicWrite,
  ) {
    this.fallbackToMemento = fallbackToMemento;
  }

  get migrationFailed(): boolean {
    return this.fallbackToMemento;
  }

  static async migrate(
    directory: string,
    state: vscode.Memento,
    writeAtomic: typeof atomicWrite = atomicWrite,
  ): Promise<MemoryStore> {
    const store = new MemoryStore(directory, state, false, undefined, writeAtomic);
    const keys = state.get<unknown>(KEYS_INDEX);
    const descriptions = state.get<unknown>(DESCRIPTIONS_INDEX);
    const descriptionMap =
      descriptions && typeof descriptions === 'object' && !Array.isArray(descriptions)
        ? (descriptions as Record<string, unknown>)
        : {};
    const entries = Array.isArray(keys)
      ? keys
          .filter(
            (key): key is string =>
              typeof key === 'string' && typeof state.get(KEY_PREFIX + key) === 'string',
          )
          .map((key) => ({
            key,
            value: state.get<string>(KEY_PREFIX + key)!,
            description: descriptionFor(
              state.get<string>(KEY_PREFIX + key)!,
              typeof descriptionMap[key] === 'string' ? (descriptionMap[key] as string) : undefined,
            ),
          }))
      : [];
    if (entries.length === 0) return store;
    try {
      const migrationTime = Date.now();
      for (const [index, entry] of entries.entries())
        store.write(
          entry.key,
          entry.value,
          entry.description,
          new Date(migrationTime + index).toISOString(),
        );
      for (const entry of entries) {
        const readBack = store.read(entry.key);
        if (!readBack || readBack.key !== entry.key || readBack.value !== entry.value) {
          throw new Error(`Verification failed for memory "${entry.key}"`);
        }
      }
      for (const entry of entries) await state.update(KEY_PREFIX + entry.key, undefined);
      await state.update(KEYS_INDEX, undefined);
      await state.update(DESCRIPTIONS_INDEX, undefined);
      store.regenerateIndex();
      return store;
    } catch (error) {
      return new MemoryStore(
        directory,
        state,
        true,
        error instanceof Error ? error.message : String(error),
      );
    }
  }

  private parsedFiles(): {
    memories: StoredMemory[];
    duplicates: StoredMemory[];
    skipped: string[];
    /** What the write loop asks about the folder, from this scan, not a new read per file. */
    names: Set<string>;
    fileKeys: Map<string, string>;
  } {
    const names = new Set<string>();
    const fileKeys = new Map<string, string>();
    if (!fs.existsSync(this.directory))
      return { memories: [], duplicates: [], skipped: [], names, fileKeys };
    const memories: StoredMemory[] = [];
    const skipped: string[] = [];
    for (const fileName of fs.readdirSync(this.directory).sort()) {
      names.add(fileName);
      if (!fileName.endsWith('.md') || fileName === 'MEMORY.md' || fileName.endsWith('.tmp'))
        continue;
      try {
        const content = fs.readFileSync(path.join(this.directory, fileName), 'utf8');
        const memory = parseMemory(fileName, content);
        fileKeys.set(fileName, memory.key);
        memories.push(memory);
      } catch (error) {
        skipped.push(
          `Skipped ${fileName}: ${error instanceof Error ? error.message : String(error)}`,
        );
      }
    }
    const counts = new Map<string, number>();
    for (const memory of memories) counts.set(memory.key, (counts.get(memory.key) ?? 0) + 1);
    const duplicated = new Set([...counts].filter(([, count]) => count > 1).map(([key]) => key));
    const duplicates: StoredMemory[] = [];
    const kept = memories.filter((memory) => {
      if (!duplicated.has(memory.key)) return true;
      // Every copy of the key is unreadable, not just the extra one: two files
      // that both say `name: dup` leave the key ambiguous, so the store answers
      // nothing for it. The copies come back as well as being skipped, because
      // `write` and `forget` below are the only thing that can make it readable
      // again, and a caller that cannot see them cannot clear them either.
      duplicates.push(memory);
      skipped.push(`Skipped ${memory.fileName}: another file has the same name "${memory.key}"`);
      return false;
    });
    return { memories: kept.sort(compareMemories), duplicates, skipped, names, fileKeys };
  }

  /**
   * Move every file carrying `key` except the one we just wrote out of the
   * store's own namespace, so the key becomes readable again.
   *
   * Until this existed the state was permanent: `parsedFiles` drops every copy
   * of a duplicated key, so `write` never saw the extras and added a third
   * file, `remember` reported success while `read` still answered nothing, and
   * `forget` said the key did not exist. Nothing is deleted here: each copy
   * goes through `quarantineCopy` below, which stops it matching the `*.md`
   * scan while keeping the owner's bytes to recover.
   *
   * `duplicates` comes from the caller's own scan: nothing but this write can
   * have changed the folder since, so a second scan re-read every file to ask
   * one question the first scan already answered.
   */
  private quarantineCopies(
    duplicates: readonly StoredMemory[],
    key: string,
    keep: string,
    freed: ReadonlySet<string>,
  ): void {
    for (const copy of duplicates) {
      if (copy.key !== key || copy.fileName === keep || freed.has(copy.fileName)) continue;
      this.quarantineCopy(copy.fileName);
    }
  }

  /**
   * Move one file out of the store's namespace without replacing anything that
   * is already there. The random suffix is not decoration: `renameSync` does
   * replace an existing target on Windows and POSIX alike, so a counter that
   * restarts at 1 on every call would let a second heal overwrite the first
   * one's backup and drop the bytes this is meant to keep.
   */
  private quarantineCopy(fileName: string): void {
    fs.renameSync(
      path.join(this.directory, fileName),
      path.join(this.directory, `${fileName}.forge-duplicate-${randomUUID()}.bak`),
    );
  }

  /** True only when a file sits at `fileName` that is NOT this key's file: the
   *  scan parsed it and it names another key, or it is there and does not parse
   *  at all. A name in `freed` was emptied by this write, so it is open. */
  private targetIsForeign(
    scan: { names: Set<string>; fileKeys: Map<string, string> },
    freed: ReadonlySet<string>,
    fileName: string,
    key: string,
  ): boolean {
    if (freed.has(fileName) || !scan.names.has(fileName)) return false;
    return scan.fileKeys.get(fileName) !== key;
  }

  list(): StoredMemory[] {
    return this.fallbackToMemento ? this.legacyEntries() : this.parsedFiles().memories;
  }

  listKeys(): string[] {
    return this.list().map(({ key }) => key);
  }

  listLines(): string[] {
    return this.list()
      .sort((a, b) => Date.parse(a.updated) - Date.parse(b.updated) || compareKeys(a.key, b.key))
      .map(({ key, description }) => renderMemoryLine(key, description));
  }

  read(key: string): StoredMemory | undefined {
    return this.list().find((memory) => memory.key === key);
  }

  async remember(key: string, value: string, description?: string): Promise<void> {
    if (!this.fallbackToMemento) {
      this.write(key, value, description);
      return;
    }
    await this.serializeLegacy(async () => {
      const keys = this.state.get<string[]>(KEYS_INDEX) ?? [];
      if (!keys.includes(key)) await this.state.update(KEYS_INDEX, [...keys, key]);
      await this.state.update(KEY_PREFIX + key, value);
      const descriptions = this.state.get<Record<string, string>>(DESCRIPTIONS_INDEX) ?? {};
      await this.state.update(DESCRIPTIONS_INDEX, {
        ...descriptions,
        [key]: descriptionFor(value, description),
      });
    });
  }

  write(
    key: string,
    value: string,
    description?: string,
    updated = new Date().toISOString(),
  ): StoredMemory {
    const desc = descriptionFor(value, description);
    // One scan per write. parsedFiles() has already dropped keys that appear in two files, so
    // the index rendered below excludes them exactly as a second scan would have. That scan also
    // carries the folder's names and keys: all the loop below needs about what is on disk.
    const { memories: files, duplicates, names, fileKeys } = this.parsedFiles();
    const all = [
      ...files.filter((memory) => memory.key !== key),
      { key, description: desc, value, fileName: '', updated },
    ];
    const colliding = new Set<string>();
    const groups = new Map<string, StoredMemory[]>();
    for (const memory of all)
      groups.set(memory.key.toLowerCase(), [
        ...(groups.get(memory.key.toLowerCase()) ?? []),
        memory,
      ]);
    for (const group of groups.values())
      if (group.length > 1) group.forEach(({ key: name }) => colliding.add(name));
    const named: StoredMemory[] = [];
    // Names this write has emptied, so a later iteration moves nothing twice.
    const freed = new Set<string>();
    let written: StoredMemory | undefined;
    for (const memory of all) {
      const safe =
        SAFE.test(memory.key) && !RESERVED.test(memory.key) && !colliding.has(memory.key);
      const fileName = safe ? `${memory.key}.md` : hashedName(memory.key);
      const target = path.join(this.directory, fileName);
      // Neither `renameSync` nor `writeAtomic` replaces quietly, so a file that
      // is not this key's has to be moved aside before either touches it: a
      // hand-renamed file, or a copy `parsedFiles` skipped, can already sit at
      // the name this key wants. `MEMORY.md` is left alone - the scan above
      // treats that exact name as the generated index, not as a memory file.
      if (
        fileName !== 'MEMORY.md' &&
        this.targetIsForeign({ names, fileKeys }, freed, fileName, memory.key)
      ) {
        this.quarantineCopy(fileName);
        freed.add(fileName);
      }
      if (memory.key !== key && memory.fileName !== fileName) {
        fs.renameSync(path.join(this.directory, memory.fileName), target);
        if (memory.fileName) freed.add(memory.fileName);
      }
      const entry: StoredMemory = { ...memory, fileName };
      if (memory.key === key) {
        this.writeAtomic(
          target,
          this.serialize(memory.key, memory.description, memory.value, updated),
        );
        written = entry;
      }
      named.push(entry);
    }
    if (written) this.quarantineCopies(duplicates, key, written.fileName, freed);
    named.sort(compareMemories);
    this.regenerateIndex(named);
    return written!;
  }

  forget(key: string): boolean {
    const { memories, duplicates } = this.parsedFiles();
    const memory = memories.find((entry) => entry.key === key);
    // A key held only by duplicated copies is invisible to `memories`, so this
    // used to answer "no such memory" while its files sat on disk. Clearing a
    // key has to clear every copy of it, or the next `remember` poisons it again.
    const copies = duplicates.filter((entry) => entry.key === key);
    if (!memory && copies.length === 0) return false;
    if (memory) fs.unlinkSync(path.join(this.directory, memory.fileName));
    copies.forEach((copy) => this.quarantineCopy(copy.fileName));
    this.regenerateIndex(memories.filter((entry) => entry !== memory));
    return true;
  }

  async forgetMemory(key: string): Promise<boolean> {
    if (!this.fallbackToMemento) return this.forget(key);
    let existed = false;
    await this.serializeLegacy(async () => {
      existed = this.read(key) !== undefined;
      await this.state.update(KEY_PREFIX + key, undefined);
      const keys = this.state.get<string[]>(KEYS_INDEX) ?? [];
      await this.state.update(
        KEYS_INDEX,
        keys.filter((entry) => entry !== key),
      );
      const descriptions = this.state.get<Record<string, string>>(DESCRIPTIONS_INDEX) ?? {};
      const next = { ...descriptions };
      delete next[key];
      await this.state.update(DESCRIPTIONS_INDEX, next);
    });
    return existed;
  }

  private serializeLegacy(work: () => Promise<void>): Promise<void> {
    const current = this.legacyPending.catch(() => undefined).then(work);
    this.legacyPending = current;
    return current;
  }

  regenerateIndex(memories: StoredMemory[] = this.parsedFiles().memories): string {
    const body = [
      INDEX_HEADER,
      ...memories.map(
        ({ key, description, fileName }) => `- [${key}](${fileName}) — ${description}`,
      ),
    ];
    this.writeAtomic(path.join(this.directory, 'MEMORY.md'), `${body.join('\n')}\n`);
    return path.join(this.directory, 'MEMORY.md');
  }

  listResult(): string {
    if (this.fallbackToMemento)
      return (
        this.legacyEntries()
          .map(({ key, description }) => renderMemoryLine(key, description))
          .join('\n') || '(no memories stored)'
      );
    const { memories, skipped } = this.parsedFiles();
    return (
      [
        ...memories.map(({ key, description }) => renderMemoryLine(key, description)),
        ...skipped,
      ].join('\n') || '(no memories stored)'
    );
  }

  private legacyEntries(): StoredMemory[] {
    const keys = this.state.get<unknown>(KEYS_INDEX);
    const descriptions = this.state.get<Record<string, unknown>>(DESCRIPTIONS_INDEX) ?? {};
    if (!Array.isArray(keys)) return [];
    const baseTime = Date.now();
    return keys.flatMap((key, index) => {
      const value = typeof key === 'string' ? this.state.get<unknown>(KEY_PREFIX + key) : undefined;
      if (typeof key !== 'string' || typeof value !== 'string') return [];
      return [
        {
          key,
          value,
          description: descriptionFor(
            value,
            typeof descriptions[key] === 'string' ? (descriptions[key] as string) : undefined,
          ),
          fileName: '',
          updated: new Date(baseTime + index).toISOString(),
        },
      ];
    });
  }

  private serialize(key: string, description: string, value: string, updated: string): string {
    return `---\nname: ${yamlString(key)}\ndescription: ${yamlString(description)}\nupdated: ${updated}\n---\n\n${value}`;
  }
}

function compareKeys(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function compareMemories(a: StoredMemory, b: StoredMemory): number {
  return compareKeys(a.key, b.key);
}

const stores = new WeakMap<vscode.Memento, MemoryStore>();

export function attachMemoryStore(state: vscode.Memento, store: MemoryStore): void {
  stores.set(state, store);
}

export function memoryStoreFor(state: vscode.Memento): MemoryStore | undefined {
  return stores.get(state);
}

export function renderMemoryLine(key: string, description?: string): string {
  if (!description) return `- ${key}`;
  const firstLine = description.split(/\r\n|\r|\n/u, 1)[0] ?? '';
  const shownDescription = firstLine.length > 120 ? `${firstLine.slice(0, 120)}…` : firstLine;
  return shownDescription ? `- ${key}: ${shownDescription}` : `- ${key}`;
}
